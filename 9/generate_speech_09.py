"""
第09期演讲稿生成脚本
《不会读文献=不会写论文，先学会"挑"文献》
以PPT为主线逐页展开，专业学术、解决具体问题、含干货，不照念PPT
"""
from docx import Document
from docx.shared import Pt, RGBColor, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn

doc=Document()
style=doc.styles['Normal']; style.font.name='宋体'; style.font.size=Pt(11)
style.element.rPr.rFonts.set(qn('w:eastAsia'),'宋体')
for sec in doc.sections:
    sec.top_margin=Inches(0.8); sec.bottom_margin=Inches(0.8)
    sec.left_margin=Inches(0.9); sec.right_margin=Inches(0.9)

NAVY=RGBColor(0x2C,0x3E,0x50); RUST=RGBColor(0x8B,0x4A,0x3A); GRAY=RGBColor(0x6E,0x68,0x60)

def heading(text,size=16,color=NAVY,sb=14,sa=6):
    p=doc.add_paragraph(); p.paragraph_format.space_before=Pt(sb); p.paragraph_format.space_after=Pt(sa)
    r=p.add_run(text); r.font.size=Pt(size); r.font.bold=True; r.font.color.rgb=color
    r.font.name='宋体'; r.element.rPr.rFonts.set(qn('w:eastAsia'),'宋体'); return p

def sub(text,size=11,color=RUST):
    p=doc.add_paragraph(); p.paragraph_format.space_before=Pt(2); p.paragraph_format.space_after=Pt(4)
    r=p.add_run(text); r.font.size=Pt(size); r.font.bold=True; r.font.color.rgb=color
    r.font.name='楷体'; r.element.rPr.rFonts.set(qn('w:eastAsia'),'楷体'); return p

def body(text,size=11,lh=1.5,indent=True):
    p=doc.add_paragraph(); p.paragraph_format.space_after=Pt(6); p.paragraph_format.line_spacing=lh
    if indent: p.paragraph_format.first_line_indent=Pt(22)
    r=p.add_run(text); r.font.size=Pt(size); r.font.name='宋体'
    r.element.rPr.rFonts.set(qn('w:eastAsia'),'宋体'); return p

def note(text):
    p=doc.add_paragraph(); p.paragraph_format.space_after=Pt(4); p.paragraph_format.left_indent=Pt(22)
    r=p.add_run(text); r.font.size=Pt(9.5); r.font.italic=True; r.font.color.rgb=GRAY
    r.font.name='楷体'; r.element.rPr.rFonts.set(qn('w:eastAsia'),'楷体'); return p

def divider():
    p=doc.add_paragraph(); p.paragraph_format.space_before=Pt(2); p.paragraph_format.space_after=Pt(2)
    r=p.add_run('— — — — — — — — — —'); r.font.size=Pt(9); r.font.color.rgb=GRAY
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER

# 封面信息
t=doc.add_paragraph(); t.alignment=WD_ALIGN_PARAGRAPH.CENTER
r=t.add_run('演讲稿 · 第九讲'); r.font.size=Pt(12); r.font.color.rgb=RUST
r.font.name='楷体'; r.element.rPr.rFonts.set(qn('w:eastAsia'),'楷体')
t2=doc.add_paragraph(); t2.alignment=WD_ALIGN_PARAGRAPH.CENTER
r=t2.add_run('不会读文献=不会写论文\n—— 先学会"挑"文献'); r.font.size=Pt(20); r.font.bold=True
r.font.color.rgb=NAVY; r.font.name='宋体'; r.element.rPr.rFonts.set(qn('w:eastAsia'),'宋体')
m=doc.add_paragraph(); m.alignment=WD_ALIGN_PARAGRAPH.CENTER
r=m.add_run('配套PPT：不会读文献先学会挑文献.ppt　|　共16页　|　预计时长：18–22分钟')
r.font.size=Pt(9.5); r.font.color.rgb=GRAY; r.font.name='楷体'
r.element.rPr.rFonts.set(qn('w:eastAsia'),'楷体')
g=doc.add_paragraph(); g.paragraph_format.space_before=Pt(8)
r=g.add_run('使用说明：本稿以PPT页码为主线逐页展开，每页标注【第X页 · 页面主题】，'
    '正文为可直接口播的讲稿，灰色斜体为节奏/互动提示。讲稿在PPT要点之上做了原理拆解、'
    '数据解读与实操延展，并非照念PPT。')
r.font.size=Pt(10); r.font.color.rgb=GRAY; r.font.name='楷体'
r.element.rPr.rFonts.set(qn('w:eastAsia'),'楷体')
divider()

